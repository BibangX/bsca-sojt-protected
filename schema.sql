CREATE SCHEMA IF NOT EXISTS portal;
CREATE TABLE IF NOT EXISTS portal.users(id TEXT PRIMARY KEY,email TEXT NOT NULL,name TEXT NOT NULL,student_number TEXT UNIQUE);
CREATE TABLE IF NOT EXISTS portal.sessions(token TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES portal.users(id),csrf TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS portal.submissions(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id TEXT NOT NULL REFERENCES portal.users(id),step TEXT NOT NULL,label TEXT NOT NULL,url TEXT NOT NULL,filename TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'submitted',note TEXT NOT NULL DEFAULT '',created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS portal.completion(user_id TEXT NOT NULL REFERENCES portal.users(id),step TEXT NOT NULL,complete INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(user_id,step));
CREATE TABLE IF NOT EXISTS portal.audit(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor TEXT NOT NULL,submission_id INTEGER,action TEXT NOT NULL,created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS portal.allowed_students(email TEXT PRIMARY KEY,active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),added_by TEXT NOT NULL,updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS portal.opened_steps(user_id TEXT NOT NULL REFERENCES portal.users(id),step TEXT NOT NULL,opened_at TEXT NOT NULL,PRIMARY KEY(user_id,step));
CREATE TABLE IF NOT EXISTS portal.auth_challenges(token TEXT PRIMARY KEY,nonce TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS portal.level_access(user_id TEXT PRIMARY KEY REFERENCES portal.users(id),early_access BOOLEAN NOT NULL DEFAULT FALSE,updated_by TEXT NOT NULL,updated_at TEXT NOT NULL);
